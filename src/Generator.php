<?php

declare(strict_types=1);

namespace Apache2Router;

/**
 * Writes the standalone router.php: the runtime classes inlined, followed by
 * the compiled configuration and a few lines of glue that run at global
 * scope (so the PHP application's own globals behave as under Apache).
 */
final class Generator
{
    /** Runtime sources, in dependency order. */
    public const RUNTIME_FILES = ['PathMapper.php', 'ConfigParser.php', 'Rewrite.php', 'Router.php'];

    /**
     * @param array<string,mixed> $config output of Compiler::compile()
     * @param list<string> $sources config files that were read
     * @param list<string> $warnings
     */
    public static function render(array $config, array $sources, array $warnings, ?string $srcDir = null): string
    {
        $srcDir ??= __DIR__;
        $code = '';
        foreach (self::RUNTIME_FILES as $f) {
            $code .= self::stripFile((string) file_get_contents($srcDir . '/' . $f)) . "\n";
        }
        $export = var_export($config, true);

        $header = self::header($config, $sources, $warnings);
        return <<<PHP
<?php

$header

declare(strict_types=1);

namespace Apache2Router {

$code
final class GeneratedConfig
{
    /** @return array<string,mixed> */
    public static function get(): array
    {
        return $export;
    }
}

}

namespace {
    if (PHP_SAPI !== 'cli-server') {
        fwrite(STDERR, "This router is for PHP's built-in server. Run:\\n  php -S 127.0.0.1:8080 " . basename(__FILE__) . "\\n");
        exit(1);
    }
    (new \\Apache2Router\\Router(\\Apache2Router\\GeneratedConfig::get()))->handle();
    if (\\Apache2Router\\Router::\$script === null) {
        return true;
    }
    require \\Apache2Router\\Router::\$script;
    return true;
}

PHP;
    }

    private static function stripFile(string $src): string
    {
        $src = (string) preg_replace('/^<\?php\s*/', '', $src);
        $src = (string) preg_replace('/^declare\(strict_types=1\);\s*/m', '', $src);
        $src = (string) preg_replace('/^namespace Apache2Router;\s*/m', '', $src);
        return trim($src) . "\n";
    }

    /**
     * @param array<string,mixed> $config
     * @param list<string> $sources
     * @param list<string> $warnings
     */
    private static function header(array $config, array $sources, array $warnings): string
    {
        $lines = [
            'Router for PHP\'s built-in web server, generated by apache2router',
            'on ' . gmdate('Y-m-d H:i') . ' UTC. Regenerate it instead of editing it.',
            '',
            'Run:  php -S 127.0.0.1:8080 ' . 'router.php',
            '',
            'Requests are matched to a virtual host by their Host header. When no',
            'name matches (e.g. "localhost:8080"), the default host below is used.',
            '',
            'Virtual hosts:',
        ];
        foreach ($config['vhosts'] as $i => $vh) {
            $names = array_merge([$vh['name'] ?? '(no ServerName)'], $vh['aliases']);
            $flag = $i === $config['default_vhost'] ? ' [default]' : '';
            $lines[] = '  ' . implode(', ', $names) . ($vh['port'] !== null ? ' :' . $vh['port'] : '') . $flag;
            $lines[] = '      DocumentRoot ' . $vh['docroot'];
        }
        if ($config['maps'] !== []) {
            $lines[] = '';
            $lines[] = 'Path maps (original => current):';
            foreach ($config['maps'] as [$old, $new]) {
                $lines[] = "  $old => $new";
            }
        }
        $lines[] = '';
        $lines[] = 'Config files read:';
        foreach ($sources as $s) {
            $lines[] = '  ' . $s;
        }
        if ($warnings !== []) {
            $lines[] = '';
            $lines[] = 'Warnings:';
            foreach ($warnings as $w) {
                foreach (explode("\n", wordwrap($w, 74, "\n", true)) as $j => $part) {
                    $lines[] = ($j === 0 ? '  - ' : '    ') . $part;
                }
            }
        }
        $out = "/*\n";
        foreach ($lines as $l) {
            $out .= rtrim(' * ' . str_replace('*/', '* /', $l)) . "\n";
        }
        return $out . ' */';
    }
}
